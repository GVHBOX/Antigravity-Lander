impl Language {
    pub fn strings(&self) -> &'static Strings {
        match self {
            Language::Zh => &ZH_STRINGS,
            Language::En => &EN_STRINGS,
        }
    }

    pub fn toggle(&mut self) {
        *self = match self {
            Language::Zh => Language::En,
            Language::En => Language::Zh,
        };
    }
}
